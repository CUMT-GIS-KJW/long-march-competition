def toc_line(doc, label, page, indent=0):
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.LEFT
    fmt = para.paragraph_format
    fmt.left_indent = Cm(0.7 * indent)
    fmt.first_line_indent = Cm(0)
    fmt.space_after = Pt(1)
    fmt.line_spacing = 1.1
    left = para.add_run(label)
    set_font(left, "宋体", 12)
    tab = para.add_run("\t")
    set_font(tab, "宋体", 12)
    right = para.add_run(str(page))
    set_font(right, "宋体", 12)
    pPr = para._p.get_or_add_pPr()
    tabs = OxmlElement("w:tabs")
    tab_stop = OxmlElement("w:tab")
    tab_stop.set(qn("w:val"), "right")
    tab_stop.set(qn("w:leader"), "dot")
    tab_stop.set(qn("w:pos"), "9000")
    tabs.append(tab_stop)
    pPr.append(tabs)


