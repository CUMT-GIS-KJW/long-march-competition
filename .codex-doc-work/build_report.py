def set_font(run, name="宋体", size=12, bold=False):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold


def set_cell_margins(cell, top=90, start=100, bottom=90, end=100):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = tcPr.first_child_found_in("w:tcMar")
    if tcMar is None:
        tcMar = OxmlElement("w:tcMar")
        tcPr.append(tcMar)
    for m, v in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = tcMar.find(qn(f"w:{m}"))
        if node is None:
            node = OxmlElement(f"w:{m}")
            tcMar.append(node)
        node.set(qn("w:w"), str(v))
        node.set(qn("w:type"), "dxa")


def set_table_borders(table, color="000000", size="6"):
    tblPr = table._tbl.tblPr
    borders = tblPr.first_child_found_in("w:tblBorders")
    if borders is None:
        borders = OxmlElement("w:tblBorders")
        tblPr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        tag = qn(f"w:{edge}")
        element = borders.find(tag)
        if element is None:
            element = OxmlElement(f"w:{edge}")
            borders.append(element)
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), size)
        element.set(qn("w:space"), "0")
        element.set(qn("w:color"), color)


def set_repeat_table_header(row):
    trPr = row._tr.get_or_add_trPr()
    hdr = OxmlElement("w:tblHeader")
    hdr.set(qn("w:val"), "true")
    trPr.append(hdr)


def clear_body(doc):
    body = doc._element.body
    sectPr = body.sectPr
    for child in list(body):
        if child is not sectPr:
            body.remove(child)


def p(doc, text="", align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_indent=True, before=0, after=2, line=1.25):
    para = doc.add_paragraph()
    para.alignment = align
    fmt = para.paragraph_format
    fmt.line_spacing = line
    fmt.space_before = Pt(before)
    fmt.space_after = Pt(after)
    if first_indent:
        fmt.first_line_indent = Cm(0.74)
    run = para.add_run(text)
    set_font(run, "宋体", 11)
    return para


def heading(doc, text, level):
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.LEFT
    fmt = para.paragraph_format
    fmt.keep_with_next = True
    fmt.keep_together = True
    fmt.space_before = Pt(10 if level == 1 else 6)
    fmt.space_after = Pt(5 if level == 1 else 3)
    run = para.add_run(text)
    if level == 1:
        set_font(run, "黑体", 18, True)
    elif level == 2:
        set_font(run, "黑体", 15, True)
    else:
        set_font(run, "黑体", 12, True)
    return para


def bullet(doc, text):
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.LEFT
    fmt = para.paragraph_format
    fmt.left_indent = Cm(0.7)
    fmt.first_line_indent = Cm(-0.45)
    fmt.line_spacing = 1.5
    fmt.space_after = Pt(2)
    run = para.add_run("➢ " + text)
    set_font(run, "宋体", 12)
    return para


def table(doc, headers, rows, widths=None):
    tb = doc.add_table(rows=1, cols=len(headers))
    tb.autofit = False
    tb.style = "Table Grid"
    set_table_borders(tb)
    hdr = tb.rows[0]
    set_repeat_table_header(hdr)
    for j, h in enumerate(headers):
        cell = hdr.cells[j]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        set_cell_margins(cell)
        para = cell.paragraphs[0]
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        para.paragraph_format.space_after = Pt(0)
        run = para.add_run(h)
        set_font(run, "黑体", 10.5, True)
    for row in rows:
        cells = tb.add_row().cells
        for j, value in enumerate(row):
            cell = cells[j]
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            set_cell_margins(cell)
            para = cell.paragraphs[0]
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER if j == 0 else WD_ALIGN_PARAGRAPH.LEFT
            para.paragraph_format.line_spacing = 1.15
            para.paragraph_format.space_after = Pt(0)
            run = para.add_run(value)
            set_font(run, "宋体", 9.5)
    if widths:
        for row in tb.rows:
            for cell, width in zip(row.cells, widths):
                cell.width = Cm(width)
    para = doc.add_paragraph()
    para.paragraph_format.space_after = Pt(4)
    return tb


